"""Daily S&P 500 closes 1994-2005 (Yahoo Finance chart API, ^GSPC) -> js/market-history-sp.js

Used only to measure how the index moved around each event on the Market History page.
Cross-checked on every run against two closes verified elsewhere (S&P DJI): 2000-03-24 = 1,527.46 and 2002-10-09 = 776.76.
Run: python scripts/market-history/fetch_sp_daily.py
"""
import datetime
import json
import os
import urllib.request

URL = 'https://query2.finance.yahoo.com/v8/finance/chart/%5EGSPC?period1=757382400&period2=1136073600&interval=1d'
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'js', 'market-history-sp.js')
CHECK = {'2000-03-24': 1527.46, '2002-10-09': 776.76}


def main():
    req = urllib.request.Request(URL, headers={'User-Agent': 'Mozilla/5.0'})
    d = json.load(urllib.request.urlopen(req, timeout=60))['chart']['result'][0]
    rows = [(datetime.datetime.fromtimestamp(t, datetime.timezone.utc).strftime('%Y-%m-%d'), c)
            for t, c in zip(d['timestamp'], d['indicators']['quote'][0]['close']) if c is not None]
    m = dict(rows)
    for k, v in CHECK.items():
        assert abs(m[k] - v) < 0.01, (k, m[k], v)
    dates = [r[0] for r in rows]
    closes = [round(r[1], 2) for r in rows]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/market-history/fetch_sp_daily.py -- do not edit by hand. Daily S&P 500 closes (Yahoo Finance ^GSPC), checked against S&P DJI closes of 2000-03-24 and 2002-10-09.\n')
        f.write('export const MHSP = ' + json.dumps({'d': dates, 'c': closes}, separators=(',', ':')) + ';\n')
    print(len(rows), 'days', dates[0], dates[-1])


if __name__ == '__main__':
    main()
