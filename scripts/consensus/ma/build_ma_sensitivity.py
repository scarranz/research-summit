# build_ma_sensitivity.py — writes js/overviews/ma-sensitivity-data.js: ONE frozen Summit model snapshot for Valuation ▸ Sensitivity, read from
# G:\My Drive\Summit\Docs\Research\DCF\Payments - All\MA\DCF MA - New.xlsm (tab Segments, annual 2025-2029; tab Discounted Cash Flow and SOTP for
# the model's own valuation reference). Frozen on purpose, not live (playbook rule 10). Regenerate when the model has a new submit.
import os,warnings,datetime
warnings.filterwarnings('ignore')
import openpyxl
HERE=os.path.dirname(os.path.abspath(__file__)); W=os.path.abspath(os.path.join(HERE,'..','..','..'))+os.sep
wb=openpyxl.load_workbook(r"G:\My Drive\Summit\Docs\Research\DCF\Payments - All\MA\DCF MA - New.xlsm",data_only=True,read_only=True)
R=list(wb['Segments'].iter_rows(max_col=20,values_only=True)); D=list(wb['Discounted Cash Flow'].iter_rows(max_col=12,values_only=True)); S=list(wb['SOTP'].iter_rows(max_col=8,values_only=True))
COL={2025:9,2026:8,2027:7,2028:6,2029:5}
def row(code=None,label=None,col=3):
    for r in R:
        if (code is not None and r[3]==code) or (label is not None and r[col]==label): return r
    raise SystemExit('not found %s %s'%(code,label))
def ser(r,mult=1,dp=3): return [round(r[COL[y]]*mult,dp) for y in sorted(COL)]
yrs=sorted(COL)
pnr=ser(row('SEG1_REV'),0.001); vas=ser(row('SEG2_REV'),0.001); op=ser(row('SEG_OPINC'),0.001); ni=ser(row('SEG_NETINC'),0.001)
sh=ser(row(label='Ending Shares',col=2),1,1); eps=ser(row('ADJ_EPS'),1,2)
# the model's own DCF reference (rows read by label, not position)
def find(rows,label,col):
    for r in rows:
        if r[col]==label: return r
    raise SystemExit(label)
sotp_wacc=find(S,'WACC',1)[2]; sotp_px=find(S,'Current Price',1)[2]
dcf93=[r for r in D if isinstance(r[3],datetime.datetime)]
today=[r for r in D if r[3]=='Today' and r[6]=='Premium'][0]
vals=[(r[3].date().isoformat() if isinstance(r[3],datetime.datetime) else str(r[3]), round(r[8],2), round(r[7],4)) for r in D if r[6]=='Premium' and isinstance(r[8],(int,float)) and (isinstance(r[3],datetime.datetime) or r[3]=='Today')]
term=[r for r in D if r[3]=='Terminal Value'][0][9]
js=lambda a:'['+', '.join(str(x) for x in a)+']'
out='''// overviews/ma-sensitivity-data.js — the frozen Summit model snapshot behind Valuation ▸ Sensitivity (PROFILE_PLAYBOOK VA-SENS, rule 10).
// GENERATED by scripts/consensus/ma/build_ma_sensitivity.py from DCF MA - New.xlsm (tab Segments), read %s. Frozen on purpose, not live:
// refresh by re-running the script when the model has a new submit. Net revenue is Payment Network plus VAS ($B); shares are the model\u2019s
// ending diluted shares (M) and EPS is net income divided by them (the model\u2019s ADJ_EPS line, which ties to Bloomberg\u2019s actual).
export var MA_SENS_MODEL = {
  asOf: '%s',
  src: 'Summit DCF model (DCF MA - New.xlsm, tab Segments), read %s; frozen, not live',
  years: %s,
  pnr:   %s,   // Payment Network net revenue, $B
  vas:   %s,   // Value-Added Services net revenue, $B
  opinc: %s,   // operating income, $B
  ni:    %s,   // net income, $B
  sh:    %s,   // ending diluted shares, M
  eps:   %s,   // model EPS, $
  dcf: { wacc: %s, terminalEvEbitda: %s, workbookPrice: %s, intrinsic: %s }   // the model\u2019s own DCF reference: [date or Today, value per share, premium of the workbook price]
};
'''%(datetime.date.today().isoformat(),datetime.date.today().isoformat(),datetime.date.today().isoformat(),js(yrs),js(pnr),js(vas),js(op),js(ni),js(sh),js(eps),round(sotp_wacc,4),term,sotp_px,'['+', '.join("['%s', %s, %s]"%v for v in vals)+']')
open(W+'js/overviews/ma-sensitivity-data.js','w',encoding='utf-8',newline='').write(out)
print(out[-700:])
