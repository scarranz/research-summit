# build_ma_histmult.py — writes js/overviews/ma-histmult-data.js (Valuation ▸ Historic Multiple denominators) and builds js/overviews/ma-histmult.js
# from js/overviews/meta-histmult.js (the guide-built copy), adapted to Mastercard.
#   EPS     BBG diluted EPS (GAAP-comparable, IS_COMP_EPS_GAAP) for the quarter, reported figure from the Bloomberg archive (results-data/ma.js `act`)
#   EBITDA  BBG comparable EBITDA for the quarter (IS_COMPARABLE_EBITDA)
#   shares  BBG diluted weighted-average shares (M)
#   cash / debt / net debt  null: the Bloomberg slots for MA carry no balance sheet, so EV/EBITDA is a gap until the 10-Q / 10-K net debt is supplied
#   published  the date of the FIRST Bloomberg snapshot that carries the print (a few days after the call), the date the chart steps each series on
import os,re,json,subprocess
HERE=os.path.dirname(os.path.abspath(__file__)); W=os.path.abspath(os.path.join(HERE,'..','..','..'))+os.sep
mx=json.load(open(HERE+'/../out/estmatrix_ma.json',encoding='utf-8'))
node=r'''
const m=await import('file:///%s'); const q=m.maResults.views.q.metrics;
console.log(JSON.stringify({p:q.rev.periods,eps:q.eps.act,ebitda:q.ebitda.act,opinc:q.opinc.act,sh:q.shares.act}));
'''%((W+'js/results-data/ma.js').replace('\\','/'))
os.makedirs(HERE+'/out',exist_ok=True); open(HERE+'/out/_hm.mjs','w',encoding='utf-8').write(node)
r=subprocess.run(['node',HERE+'/out/_hm.mjs'],capture_output=True,text=True,encoding='utf-8')
if r.returncode: raise SystemExit(r.stderr)
D=json.loads(r.stdout)
first={}
for v in mx['vintages']:
    first.setdefault(v['lastActual']['q'],v['id'])
def qend(p):   # '2Q26' -> 2026-06-30
    q=int(p[0]); y=2000+int(p[2:]); return '%d-%s'%(y,{1:'03-31',2:'06-30',3:'09-30',4:'12-31'}[q])
rows=[]
for i,p in enumerate(D['p']):
    if D['eps'][i] is None or p not in first: continue
    rows.append("  ['%s','%s','%s', %s, %s, %s, %s, null, null, null],"%(p,qend(p),first[p],D['eps'][i],D['ebitda'][i],D['opinc'][i],D['sh'][i]))
data='''// ma-histmult-data.js — Mastercard quarterly denominators for Valuation ▸ Historic Multiple (VA-HIST, playbook §14).
//
// Source: the REPORTED values carried in the Bloomberg consensus export (BBG_CONSENSUS.txt; where a quarter appears in several
// snapshots the newest wins), via js/results-data/ma.js. They are reported figures (rule 10 allows them in a file). Generated by
// scripts/consensus/ma/build_ma_histmult.py; not typed.
//   EPS      diluted EPS for the quarter, the Bloomberg GAAP-comparable line (IS_COMP_EPS_GAAP): Q2 2026 is 4.97 against the
//            company-adjusted 5.04, so trailing P/E here reads slightly above the P/E on adjusted EPS.
//   EBITDA   Bloomberg comparable EBITDA (US$ M).
//   shares   weighted diluted shares for the quarter (millions).
//   cash / debt / net debt  EMPTY: the Bloomberg export for MA has no balance-sheet slots. EV/EBITDA is therefore a gap (never a made-up
//            zero) until the net debt from the 10-Q / 10-K is supplied; the chart shows P/E only until then.
// The "published" date is the date of the first Bloomberg snapshot that carries the print, a few days after the call; the chart steps
// each series on that date.
// [quarter, period end, published, EPS, EBITDA, operating income, shares, cash, debt, net debt] \u2014 US$ million (EPS in $)
export var MA_HM_Q = [
%s
];
'''%('\n'.join(rows))
open(W+'js/overviews/ma-histmult-data.js','w',encoding='utf-8',newline='').write(data)
# ---- the module
s=open(W+'js/overviews/meta-histmult.js',encoding='utf-8',newline='').read().replace('\r\n','\n')
s=s.replace("metaResults","maResults").replace("'../results-data/meta.js'","'../results-data/ma.js'").replace("META_HM_Q","MA_HM_Q").replace("./meta-histmult-data.js","./ma-histmult-data.js").replace("metaHistMult","maHistMult")
# price: one ticker, no rename splice
a=s.index("  // Meta traded as FB until June 8, 2022"); b=s.index("    .then(function(priceRes){")
s=s[:a]+"  function get(tk, a, b){ return fetchPriceHistory(tk, a, b).catch(function(e){ return { success:false, error:{message:(e&&e.message)||'price fetch failed'} }; }); }\n  return get('MA', START, TODAY)\n"+s[b:]
s=s.replace("the price service returned no rows for META","the price service returned no rows for MA").replace("This chart reads META\\'s daily close","This chart reads MA\\'s daily close")
s=s.replace("Fiscal years are calendar years for Meta","Fiscal years are calendar years for Mastercard").replace("tailored","tailored")
# header comment
h=s.index('import {');
hdr='''// overviews/ma-histmult.js — Mastercard (MA) Deep Dive ▸ Valuation ▸ Historic Multiple (VA-HIST, playbook §14).
//
// COPIED from js/overviews/meta-histmult.js (itself the TSM/AMZN copy), then adapted to Mastercard: one price series (MA, live from Massive via
// get-market-history), reported EPS, EBITDA and shares from ./ma-histmult-data.js (Bloomberg reported values) and forward EPS and EBITDA from the
// Bloomberg estMatrix in js/results-data/ma.js. Net debt is EMPTY (no balance sheet in the Bloomberg export), so the EV/EBITDA lines are a gap
// until the filings supply it and the chart shows P/E; the module already treats a missing net debt as a gap, never as zero.
// Styles: css/overview.css (.hm-* rules shared via :is(.ov-tsm-dd, .ov-meta-dd, .ov-sofi-dd, .ov-mastercard-dd)).
'''
s=hdr+s[h:]
# footer text
a=s.index("  var nd=MA_HM_Q, n0=nd[0], n1=nd[nd.length-1]"); b=s.index("// ── Render ──")
foot='''  var nd=MA_HM_Q, n0=nd[0], n1=nd[nd.length-1], vs=maResults.estMatrix.cons.vintages;
  return '<b>How the lines are built.</b> Each is a price divided by a number that stood on that day: '+
    '<b>P/E</b> = price \\u00f7 EPS, <b>EV/EBITDA</b> = (price \\u00d7 diluted shares + net debt) \\u00f7 EBITDA, on every business day. '+
    '<b>Forward</b> takes the estimate for the period you pick, <b>trailing</b> takes what Mastercard had already reported. '+
    'The denominator is a <b>step series</b>: it changes only when the Street revises, or when the period it is FOR rolls forward \\u2014 '+
    'the vertical drops in a forward-multiple chart are that roll, not a re-rating. '+
    '<b>NTM</b> blends FY0 \\u00d7 (days left in FY0 \\u00f7 365) + FY1 \\u00d7 the rest, so it slides instead of stepping. '+
    'Quarterly and annual points are the <b>average</b> over the period. '+
    '<b>Sources.</b> Price: Massive daily close (live). Consensus EPS and EBITDA: Bloomberg consensus export, one vintage per print ('+
    esc(vs[0].id)+' to '+esc(vs[vs.length-1].id)+'). Reported EPS, EBITDA and diluted shares: the same Bloomberg export ('+
    esc(n0[0])+'\\u2013'+esc(n1[0])+'), stepped on the first snapshot that carries each print. EPS is the GAAP-comparable line ($4.97 in 2Q26 against the company-adjusted $5.04). '+
    '<b>EV/EBITDA is not drawn yet:</b> net debt comes from the 10-Q / 10-K balance sheet and is not in the Bloomberg export, so that line stays empty until the filings are loaded.';
}

'''
s=s[:a]+foot+s[b:]
open(W+'js/overviews/ma-histmult.js','w',encoding='utf-8',newline='').write(s)
print(len(rows),'quarters; module written')
