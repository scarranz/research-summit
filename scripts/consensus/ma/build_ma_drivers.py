# build_ma_drivers.py — writes js/results-data/ma-drivers.js (Top Line ▸ Drivers) from the Summit DCF workbook
# G:\My Drive\Summit\Docs\Research\DCF\Payments - All\MA\DCF MA - New.xlsm, tab Segments (annual 2018-2029). Model actuals through 2025
# are the reported figures (cards, purchase volume and switched transactions tie to the Bloomberg actuals); 2026-2029 are the model's
# own projections, frozen on purpose (playbook rule 10) with the read date in the header. Annual only: the model has no quarterly build.
import os,warnings,datetime,math
warnings.filterwarnings('ignore')
import openpyxl
HERE=os.path.dirname(os.path.abspath(__file__))
W=os.path.abspath(os.path.join(HERE,'..','..','..'))+os.sep
wb=openpyxl.load_workbook(r"G:\My Drive\Summit\Docs\Research\DCF\Payments - All\MA\DCF MA - New.xlsm",data_only=True,read_only=True)
R=list(wb['Segments'].iter_rows(max_col=20,values_only=True))
YEARS=list(range(2018,2030)); COL={2029:5,2028:6,2027:7,2026:8,2025:9,2024:10,2023:11,2022:12,2021:13,2020:14,2019:15,2018:16}
def row(code=None,label=None,col=3,nth=1):
    n=0
    for i,r in enumerate(R):
        if code is not None and r[col]==code: n+=1
        elif label is not None and r[col]==label: n+=1
        else: continue
        if n==nth: return r
    raise SystemExit('row not found %s %s'%(code,label))
def series(r,mult=1,dp=0):
    out=[]
    for y in YEARS:
        v=r[COL[y]]
        out.append(None if not isinstance(v,(int,float)) else (round(v*mult) if dp==0 else round(v*mult,dp)))
    return out
# (key, label, short, group, unit, row, mult, dp, note)
M=[
 ('cus','US credit cards','US credit','Cards in market','cnt',row('US_CREDIT_CARDS'),1,0,'Mastercard- and Maestro-branded credit cards issued in the US, millions. Model actuals through 2025; Summit projection after.'),
 ('cud','US debit cards','US debit','Cards in market','cnt',row('US_DEBIT_CARDS'),1,0,'Debit cards issued in the US, millions. The Capital One debit migration is in the model history.'),
 ('cic','International credit cards','Intl credit','Cards in market','cnt',row('INTL_CREDIT_CARDS'),1,0,'Credit cards issued outside the US, millions.'),
 ('cid','International debit cards','Intl debit','Cards in market','cnt',row('INTL_DEBIT_CARDS'),1,0,'Debit cards issued outside the US, millions.'),
 ('vus','US credit purchase volume','US credit','Purchase volume','usdM',row('US_CRED_PURCH_VOL'),1000,0,'Purchase volume on US credit cards. The model stores $B; shown here in $M like the rest of the profile.'),
 ('vud','US debit purchase volume','US debit','Purchase volume','usdM',row('US_DEB_PURCH_VOL'),1000,0,'Purchase volume on US debit cards.'),
 ('vic','International credit purchase volume','Intl credit','Purchase volume','usdM',row('INTL_CRED_PURCH_VOL'),1000,0,'Purchase volume on credit cards outside the US.'),
 ('vid','International debit purchase volume','Intl debit','Purchase volume','usdM',row('INTL_DEB_PURCH_VOL'),1000,0,'Purchase volume on debit cards outside the US.'),
 ('vtot','Purchase volume, total','Purchase volume','Purchase volume','usdM',row(label='Purchase Volume',col=2),1000,0,'Total purchase volume across the network, the sum of the four lines above.'),
 ('ptx','Processed (switched) transactions','Processed txns','Network activity','cnt',row('SWITCH_TRANS'),1,0,'Switched transactions, millions. The model carries 175.5B for 2025 and 192.2B for 2026.'),
 ('emp','Employees','Employees','Network activity','count',row('EMPLOYEES'),1,0,'Headcount used by the model to build personnel cost.'),
 ('gy','Gross yield','Gross yield','Yield (% of purchase volume)','pct',row(label='Gross Yield',col=2),100,3,'Gross revenue as a percentage of purchase volume, from the model.'),
 ('ny','Net yield','Net yield','Yield (% of purchase volume)','pct',row(label='Net Yield',col=2),100,3,'Net revenue as a percentage of purchase volume, from the model.'),
 ('iy','Incentive yield','Incentive yield','Yield (% of purchase volume)','pct',row(label='Incentive Yield',col=2),100,3,'Client incentives as a percentage of purchase volume, from the model; it rises through 2029 in the model.'),
]
# the labelled yield rows may carry the label in col 1; fall back
def find_label(lbl):
    for r in R:
        if lbl in (r[1],r[2],r[3]): return r
    raise SystemExit(lbl)
M=[(k,l,s,g,u,(r if r else None),m,d,n) for (k,l,s,g,u,r,m,d,n) in M]
def js(a): return '['+', '.join('null' if v is None else str(v) for v in a)+']'
def esc(t): return t.replace('\\','\\\\').replace("'","\\'")
P=[str(y) for y in YEARS]
out=[]
out.append("""// results-data/ma-drivers.js — Mastercard "Top Line ▸ Drivers" dataset for the Results ENGINE: cards in market, purchase volume by region and
// product, switched transactions, headcount and yield. GENERATED by scripts/consensus/ma/build_ma_drivers.py from the Summit DCF workbook
// (DCF MA - New.xlsm, tab Segments, read %s). Frozen on purpose, not live (playbook rule 10). Annual only: the model has no quarterly build.
//   act    — the model's history, 2018-2025 (the reported figures; purchase volume, cards and switched transactions tie to Bloomberg)
//   summit — the model's own projections, 2026-2029
// There is no Street consensus for these series. Mastercard gives no guidance on them. Regenerate, do not hand-edit.
export var maDrivers = {
  updated: 'Oct 2026',
  source: 'Summit DCF model, DCF MA - New.xlsm, tab Segments, read %s; frozen, not live. History = the model\\u2019s reported actuals; 2026\\u20132029 = the model\\u2019s projections.',
  views: {
    y: {
      label: 'Annual',
      note: 'The Summit model\\u2019s operating build, annual: reported history to 2025 and the model\\u2019s own projection after. Purchase volume is stored in $B in the model and shown here in $M. Cards are in millions.',
      metrics: {"""%((datetime.date.today().isoformat(),)*2))
for i,(k,l,s,g,u,r,m,d,n) in enumerate(M):
    vals=series(r,m,d)
    act=[v if y<=2025 else None for v,y in zip(vals,YEARS)]
    sm=[v if y>=2026 else None for v,y in zip(vals,YEARS)]
    out.append("        %s: { label: '%s', short: '%s', group: '%s', unit: '%s',"%(k,esc(l),esc(s),esc(g),u))
    out.append("          periods: [%s],"%', '.join("'%s'"%p for p in P))
    out.append("          act:    %s,"%js(act))
    out.append("          summit: %s,"%js(sm))
    out.append("          cons:   %s,"%js([None]*len(P)))
    out.append("          guideLo:%s,"%js([None]*len(P)))
    out.append("          guideHi:%s,"%js([None]*len(P)))
    out.append("          note: '%s' },"%esc(n))
out.append("""      },
      sections: [
        { key: 'drcards', label: 'Cards in market', defaultMetric: 'cus', groups: [ { label: 'Cards in market', keys: ['cus', 'cud', 'cic', 'cid'] } ] },
        { key: 'drvol', label: 'Purchase volume', defaultMetric: 'vtot', groups: [ { label: 'Total', keys: ['vtot'] }, { label: 'By region and product', keys: ['vus', 'vud', 'vic', 'vid'] } ] },
        { key: 'dract', label: 'Network activity and yield', defaultMetric: 'ptx', groups: [ { label: 'Network activity', keys: ['ptx', 'emp'] }, { label: 'Yield (% of purchase volume)', keys: ['gy', 'ny', 'iy'] } ] }
      ]
    }
  }
};
""")
open(W+'js/results-data/ma-drivers.js','w',encoding='utf-8',newline='').write('\n'.join(out))
print('written ma-drivers.js')
